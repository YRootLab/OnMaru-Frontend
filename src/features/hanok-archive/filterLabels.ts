/*
  필터 값 → 화면에 보일 이름.

  필터 문자열은 라벨이 아니라 데이터 값이다. `village.type`, `village.badges`와
  글자 하나까지 같아야 필터가 걸리므로, 값을 바꾸면 필터가 조용히 아무것도 못 거른다.

  그래서 값은 그대로 두고 보이는 이름만 여기서 갈아 끼운다.
  유형 바와 태그 바가 같은 것을 다르게 부르던 문제를 이 표 하나로 맞춘다.

  유형 값은 관광공사 분류표의 공식 명칭을 그대로 쓴다(고택·민속마을·고궁·생가·문).
  그중 '문'만 한 글자라 칩으로 읽히지 않아 화면에서 늘려 부른다.

  단 '고택'(A02010400) 하나는 서비스 쪽에서 한 번 더 가른다 — 살림집인 고택과
  강학 공간인 서원·향교는 건축 목적이 다른데 관광공사 코드는 하나뿐이라서다.
  갈라내는 규칙은 hanokArchive.service.ts의 classifyHeritageHouse를 볼 것.

    유형 값        →  화면
    문                성문·문루   (21건 중 19건이 성문·궁문·관문이다. 효자문 2건은 분류 자체의 잡음)
    한옥스테이         한옥 스테이   (숙소일 뿐 고택이 아닌 곳도 섞여 있다. '고택 스테이'라 부르면
                                   사실과 다른 말을 하게 된다 — 그냥 띄어 쓴 원래 값)
*/

const FILTER_LABELS: Record<string, string> = {
  '문': '성문과 누각',
  '한옥스테이': '한옥 숙소',
  '서원·향교': '서원과 향교',
  '전통체험': '전통 체험',
};

/** 필터 값에 붙은 화면 이름. 표에 없으면 값을 그대로 쓴다. */
export function filterLabel(value: string): string {
  return FILTER_LABELS[value] ?? value;
}
